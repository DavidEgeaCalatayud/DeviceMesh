#!/usr/bin/env python3
"""Render a deterministic Markdown endpoint catalog from the FastAPI application."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

from app.main import app  # noqa: E402

METHOD_ORDER = {"get": 0, "post": 1, "put": 2, "patch": 3, "delete": 4, "options": 5, "head": 6}


def _escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def render() -> str:
    schema: dict[str, Any] = app.openapi()
    operations: list[tuple[str, str, str, str, str]] = []
    for path, path_item in schema.get("paths", {}).items():
        for method, operation in path_item.items():
            if method not in METHOD_ORDER or not isinstance(operation, dict):
                continue
            tags = ", ".join(operation.get("tags", [])) or "untagged"
            summary = str(operation.get("summary") or operation.get("operationId") or "")
            responses = ", ".join(sorted(str(code) for code in operation.get("responses", {})))
            operations.append((path, method, tags, summary, responses))

    operations.sort(key=lambda item: (item[0], METHOD_ORDER[item[1]], item[1]))
    lines = [
        "# DeviceMesh REST Endpoint Catalog",
        "",
        "> Generated by `python tools/docs/render_api_catalog.py`. Do not edit rows by hand; regenerate after API changes.",
        "",
        f"Documented OpenAPI operations: **{len(operations)}**.",
        "",
        "| Method | Path | Tag | Summary | Declared responses |",
        "|---|---|---|---|---|",
    ]
    for path, method, tags, summary, responses in operations:
        lines.append(
            f"| `{method.upper()}` | `{_escape(path)}` | {_escape(tags)} | {_escape(summary)} | {_escape(responses)} |"
        )

    lines.extend(
        [
            "",
            "## Runtime endpoints outside the OpenAPI operation list",
            "",
            "| Protocol | Path | Purpose |",
            "|---|---|---|",
            "| `GET` | `/metrics` | Protected Prometheus exposition endpoint (`include_in_schema=False`). |",
            "| `WebSocket` | `/ws/events` | Authenticated/public-read event stream according to deployment policy. |",
            "",
            "FastAPI's framework documentation endpoints (`/openapi.json`, `/docs`, `/redoc`) are generated automatically and are not treated as DeviceMesh product operations in the count above.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "docs/api/ENDPOINT_CATALOG.md")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
